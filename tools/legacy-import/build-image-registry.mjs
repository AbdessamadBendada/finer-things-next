/**
 * Reads intrinsic dimensions of every asset in public/assets and emits a typed
 * image registry. next/image needs width+height for every non-fill image;
 * hardcoding them by hand would be both tedious and a source of CLS bugs.
 *
 *   pnpm migrate:images
 */
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import sharp from 'sharp';

const ASSETS_DIR = path.resolve('public/assets');
const OUT_FILE = path.resolve('src/shared/config/image-registry.ts');
const IMAGE_EXT = new Set(['.webp', '.png', '.jpg', '.jpeg', '.avif']);

const files = (await readdir(ASSETS_DIR))
  .filter((file) => IMAGE_EXT.has(path.extname(file).toLowerCase()))
  .sort();

const entries = [];
for (const file of files) {
  const { width, height } = await sharp(path.join(ASSETS_DIR, file)).metadata();
  if (!width || !height) throw new Error(`Could not read dimensions for ${file}`);
  entries.push({ src: `/assets/${file}`, width, height });
}

const body = entries
  .map((e) => `  '${e.src}': { width: ${e.width}, height: ${e.height} },`)
  .join('\n');

await writeFile(
  OUT_FILE,
  `/**
 * GENERATED by tools/legacy-import/build-image-registry.mjs — do not edit.
 * Run \`pnpm migrate:images\` after adding or replacing an asset.
 */

export type ImageDimensions = { width: number; height: number };

export const IMAGE_REGISTRY = {
${body}
} as const satisfies Record<string, ImageDimensions>;

export type RegisteredImage = keyof typeof IMAGE_REGISTRY;

/**
 * Intrinsic size lookup. Throws at build time on an unknown path so a typo in
 * an asset name can never ship as a silently broken image.
 */
export function imageSize(src: RegisteredImage): ImageDimensions {
  const size = IMAGE_REGISTRY[src];
  if (!size) throw new Error(\`Unknown image asset: \${src}\`);
  return size;
}
`,
  'utf8',
);

console.log(
  `Wrote ${entries.length} image entries to ${path.relative(process.cwd(), OUT_FILE)}`,
);
